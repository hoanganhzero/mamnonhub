import fs from 'node:fs/promises';
import XLSX from 'xlsx';
import ExcelJS from 'exceljs';
import { downloadStyledRegister } from '../lib/styled-register.ts';
const book=XLSX.readFile('public/templates/so-theo-doi-tre-mam-non.xls');
book.Sheets.SYLL.P6={t:'s',v:'0395848516'};
book.Sheets.SYLL.E6={t:'s',v:'07/04/2023'};
book.Sheets['từng tháng'].D4={t:'s',v:'N'};
book.Sheets['từng tháng'].E4={t:'s',v:'S'};
book.Sheets['từng tháng'].F4={t:'s',v:'C'};
let blob;
globalThis.fetch=async()=>new Response(await fs.readFile('public/templates/so-theo-doi-tre-mam-non.xlsx'));
globalThis.document={createElement:()=>({click(){},remove(){}}),body:{appendChild(){}}};
URL.createObjectURL=(value)=>{blob=value;return 'blob:test';};
globalThis.setTimeout=()=>0;
await downloadStyledRegister(book,'test.xlsx');
const bytes=await blob.arrayBuffer();
await fs.writeFile('/tmp/syll-format/verified-export.xlsx',new Uint8Array(bytes));
const wb=new ExcelJS.Workbook(); await wb.xlsx.load(bytes);
const syll=wb.getWorksheet('SYLL'), month=wb.getWorksheet('từng tháng');
if(syll.getCell('P6').value!=='0395848516') throw new Error('Phone lost leading zero');
if(syll.getCell('D6').font.name!=='Times New Roman') throw new Error('Font missing');
if(!syll.getCell('D6').border.left?.style) throw new Error('Border missing');
if(syll.getCell('E6').numFmt!=='dd/mm/yyyy') throw new Error('Date format missing');
if(syll.getCell('E6').value.toISOString().slice(0,10)!=='2023-04-07') throw new Error('Date changed');
if(month.getCell('D4').value!=='N'||month.getCell('E4').value!=='S'||month.getCell('F4').value!=='C') throw new Error('Attendance code lost');
if(month.pageSetup.orientation!=='landscape'||month.pageSetup.fitToWidth!==1) throw new Error('Print settings missing');
if(month.getCell('R42').value!=='    GIÁO VIÊN CHỦ NHIỆM') throw new Error('Signature label changed');
console.log(JSON.stringify({sheets:wb.worksheets.length,font:syll.getCell('D6').font.name,borders:syll.getCell('D6').border,alignment:syll.getCell('D6').alignment,dateFormat:syll.getCell('E6').numFmt,printArea:month.pageSetup.printArea,orientation:month.pageSetup.orientation,width:syll.getColumn(4).width,rowHeight:syll.getRow(6).height,passed:true}));
